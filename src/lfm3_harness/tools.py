_SKIP_DIR_NAMES = frozenset({".git", "__pycache__", ".pytest_cache", ".mypy_cache", "node_modules"})
_STOP_WORDS = frozenset({"the", "and", "for", "with", "this", "that", "from", "return", "true", "false", "none"})
_WORD_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]{2,}")


@dataclass(frozen=True)
class ToolSpec:
    """Schema metadata for a single agent tool."""

    name: str
    description: str
    parameters: Dict[str, Any]
    kind: str  # "read" | "staged_write" | "sense"
    required_capability: Optional[str] = None

    def to_openai_schema(self) -> Dict[str, Any]:
        return {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": self.parameters,
            },
        }


@dataclass(frozen=True)
class StagedWriteProposal:
    """Diff proposal generated by write_file/edit_file without modifying disk."""

    tool_name: str
    rel_path: str
    base_sha256: str
    new_content: str
    diff: str
    bytes_new: int
    reason: str = ""


@dataclass(frozen=True)
class ToolResult:
    """Structured tool return value consumed by the harness and protocol renderer."""

    ok: bool
    tool_name: str
    content: str
    error: Optional[str] = None
    staged_proposal: Optional[StagedWriteProposal] = None


