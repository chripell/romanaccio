def get_tool_specs(
    capabilities: Optional[Capabilities] = None,
    *,
    include_job_tools: bool = False,
) -> List[ToolSpec]:
    """Return enabled tool specifications in canonical sorted order."""
    caps = capabilities or Capabilities()
    combined: Dict[str, ToolSpec] = dict(_ALL_TOOL_SPECS)
    if include_job_tools:
        combined.update(_JOB_TOOL_SPECS)
    specs: List[ToolSpec] = []
    for name in sorted(combined):
        spec = combined[name]
        if spec.required_capability == "vision" and not caps.vision:
            continue
        if spec.required_capability == "voice_asr" and not caps.voice_asr:
            continue
        specs.append(spec)
    return specs


def get_tool_schemas(
    capabilities: Optional[Capabilities] = None,
    *,
    include_job_tools: bool = False,
) -> List[Dict[str, Any]]:
    """Return canonical sorted OpenAI-style function tool schemas for prefix stability."""
    return [spec.to_openai_schema() for spec in get_tool_specs(capabilities, include_job_tools=include_job_tools)]


def _clip_text(text: str, limit: int = MAX_OUTPUT_CHARS) -> Tuple[str, bool]:
    if len(text) <= limit:
        return text, False
    clipped = text[: max(0, limit - 48)] + f"\n...[truncated at {limit} chars]"
    return clipped, True


def _extract_terms(text: str) -> Set[str]:
    terms: Set[str] = set()
    for m in _WORD_RE.finditer(text):
        tok = m.group(0).lower()
        if tok not in _STOP_WORDS:
            terms.add(tok)
    return terms


def _make_unified_diff(rel_path: str, old_text: str, new_text: str) -> str:
    old_lines = old_text.splitlines(keepends=True)
    new_lines = new_text.splitlines(keepends=True)
    return "".join(
        difflib.unified_diff(
            old_lines,
            new_lines,
            fromfile=f"a/{rel_path}",
            tofile=f"b/{rel_path}",
            lineterm="\n",
        )
    )


class ToolExecutor:
    """Executes confined read/staged-write tools inside a WorkspaceSandbox."""

    def __init__(
        self,
        sandbox: WorkspaceSandbox,
        capabilities: Optional[Capabilities] = None,
        limits: Optional[SafetyLimits] = None,
    ):
        self.sandbox = sandbox
        self.capabilities = capabilities or Capabilities()
        self.limits = limits or SafetyLimits()

    def _iter_safe_files(self, start_dir: Path, *, max_depth: int = 8) -> Iterable[Path]:
        """Yield sorted non-symlink regular files under start_dir without traversing symlinks."""
        stack: List[Tuple[Path, int]] = [(start_dir, 0)]
        while stack:
            cur_dir, depth = stack.pop()
            try:
                children = sorted(cur_dir.iterdir(), key=lambda p: p.name)
            except OSError:
                continue
            dirs_to_push: List[Path] = []
            for entry in children:
                if entry.is_symlink():
                    continue
                if entry.name.startswith(".lfm3_tmp_"):
                    continue
                if entry.is_dir():
                    if entry.name in _SKIP_DIR_NAMES:
                        continue
                    if depth < max_depth:
                        dirs_to_push.append(entry)
                elif entry.is_file():
                    yield entry
            # Push in reverse sorted order so depth-first pop visits in alphabetical order.
            for d in reversed(dirs_to_push):
                stack.append((d, depth + 1))

    def _read_utf8_capped(self, path: Path) -> Tuple[Optional[str], Optional[str]]:
        size = path.stat().st_size
        if size > self.limits.max_read_bytes:
            return None, f"File exceeds max_read_bytes ({size} > {self.limits.max_read_bytes})"
        raw = path.read_bytes()
        if b"\x00" in raw:
            return None, "File appears to be binary (contains NUL bytes)"
        return raw.decode("utf-8", errors="replace"), None

    def execute(
        self,
        name: str,
        arguments: Optional[Dict[str, Any]] = None,
        *,
        allowed_tools: Optional[Sequence[str]] = None,
    ) -> ToolResult:
        """Execute a tool call with capability checks, phase gating, and sandbox enforcement."""
        args = arguments if isinstance(arguments, dict) else {}
        spec = _ALL_TOOL_SPECS.get(name)
        if spec is None:
            return ToolResult(ok=False, tool_name=name, content="", error=f"Unknown or forbidden tool: {name}")

        if spec.required_capability == "vision" and not self.capabilities.vision:
            return ToolResult(ok=False, tool_name=name, content="", error="Tool 'look' disabled (vision unavailable)")
        if spec.required_capability == "voice_asr" and not self.capabilities.voice_asr:
            return ToolResult(ok=False, tool_name=name, content="", error="Tool 'transcribe' disabled (ASR unavailable)")

        if allowed_tools is not None and name not in allowed_tools:
            return ToolResult(
                ok=False,
                tool_name=name,
                content="",
                error=f"Tool '{name}' is not permitted in the current execution phase",
            )

        try:
            if name == "list_files":
                return self._run_list_files(args)
            if name == "read_file":
                return self._run_read_file(args)
            if name == "search_files":
                return self._run_search_files(args)
            if name == "related_files":
                return self._run_related_files(args)
            if name == "write_file":
                return self._run_write_file(args)
            if name == "edit_file":
                return self._run_edit_file(args)
            if name in ("look", "transcribe"):
                return self._run_sense_probe(name, args)
        except PathSandboxError as exc:
            return ToolResult(ok=False, tool_name=name, content="", error=f"Sandbox violation ({exc.reason}): {exc}")
        except Exception as exc:
            return ToolResult(ok=False, tool_name=name, content="", error=f"Tool execution error: {exc}")

        return ToolResult(ok=False, tool_name=name, content="", error=f"Unhandled tool: {name}")

    def _run_list_files(self, args: Dict[str, Any]) -> ToolResult:
        rel = str(args.get("path", ".") or ".")
        max_depth = max(1, min(10, int(args.get("max_depth", 3))))
        cap = max(1, min(self.limits.max_list_entries, int(args.get("max_entries", 200))))
        base_dir = self.sandbox.resolve_dir(rel, must_exist=True)

        entries: List[Dict[str, Any]] = []
        truncated = False
        queue: List[Tuple[Path, int]] = [(base_dir, 0)]
        while queue and not truncated:
            cur, depth = queue.pop(0)
            try:
                children = sorted(cur.iterdir(), key=lambda p: (not p.is_dir(), p.name))
            except OSError:
                continue
            for child in children:
                if child.is_symlink() or child.name.startswith(".lfm3_tmp_"):
                    continue
                is_dir = child.is_dir()
                if is_dir and child.name in _SKIP_DIR_NAMES:
                    continue
                rel_child = self.sandbox.relativize(child)
                info: Dict[str, Any] = {
                    "path": rel_child,
                    "type": "dir" if is_dir else "file",
                }
                if not is_dir and child.is_file():
                    info["bytes"] = child.stat().st_size
                entries.append(info)
                if len(entries) >= cap:
                    truncated = True
                    break
                if is_dir and depth + 1 < max_depth:
                    queue.append((child, depth + 1))

        payload = {
            "root": "." if base_dir == self.sandbox.root else self.sandbox.relativize(base_dir),
            "count": len(entries),
            "truncated": truncated,
            "entries": entries,
        }
        return ToolResult(ok=True, tool_name="list_files", content=json.dumps(payload))

    def _run_read_file(self, args: Dict[str, Any]) -> ToolResult:
        rel = str(args.get("path") or "").strip()
        if not rel:
            return ToolResult(
                ok=False,
                tool_name="read_file",
                content="",
                error="Missing required 'path' parameter. Pass relative file path, e.g. path='inbox/notes.txt'.",
            )
        try:
            target = self.sandbox.resolve_read(rel)
        except PathSandboxError as exc:
            if exc.reason == "not_found":
                avail = [self.sandbox.relativize(p) for p in self._iter_safe_files(self.sandbox.root, max_depth=4)][:12]
                return ToolResult(
                    ok=False,
                    tool_name="read_file",
                    content="",
                    error=f"Sandbox violation (not_found): {exc}. Existing workspace files: {avail}",
                )
            raise
        text, err = self._read_utf8_capped(target)
        if err is not None or text is None:
            return ToolResult(ok=False, tool_name="read_file", content="", error=err or "Unreadable file")

        lines = text.splitlines()
        total_lines = len(lines)
        start_line = int(args.get("start_line") or 1)
        end_line = int(args.get("end_line") or max(1, total_lines))
        start_line = max(1, start_line)
        end_line = min(max(1, total_lines), end_line)
        if total_lines > 0 and start_line <= end_line:
            selected = "\n".join(lines[start_line - 1 : end_line])
        else:
            selected = ""

        clipped, was_clipped = _clip_text(selected, self.limits.max_output_chars)
        payload = {
            "path": self.sandbox.relativize(target),
            "bytes": target.stat().st_size,
            "sha256": self.sandbox.sha256_file(target),
            "total_lines": total_lines,
            "start_line": start_line,
            "end_line": end_line,
            "truncated": was_clipped,
            "content": clipped,
        }
        return ToolResult(ok=True, tool_name="read_file", content=json.dumps(payload))

    def _run_search_files(self, args: Dict[str, Any]) -> ToolResult:
        query = str(args.get("query") or "")
        if not query:
            return ToolResult(ok=False, tool_name="search_files", content="", error="Query must be non-empty")
        rel = str(args.get("path", ".") or ".")
        case_sensitive = bool(args.get("case_sensitive", False))
        cap = max(1, min(self.limits.max_search_results, int(args.get("max_results", MAX_SEARCH_RESULTS))))
        base_dir = self.sandbox.resolve_dir(rel, must_exist=True)

        needle = query if case_sensitive else query.lower()
        matches: List[Dict[str, Any]] = []
        for fpath in self._iter_safe_files(base_dir):
            rel_f = self.sandbox.relativize(fpath)
            hay_name = rel_f if case_sensitive else rel_f.lower()
            if needle in hay_name:
                matches.append({"file": rel_f, "line": 0, "text": f"[filename match] {rel_f}"})
                if len(matches) >= cap:
                    break
            text, err = self._read_utf8_capped(fpath)
            if err is not None or text is None:
                continue
            for idx, line in enumerate(text.splitlines(), start=1):
                hay_line = line if case_sensitive else line.lower()
                if needle in hay_line:
                    matches.append({"file": rel_f, "line": idx, "text": line[:240]})
                    if len(matches) >= cap:
                        break
            if len(matches) >= cap:
                break

        payload = {"query": query, "count": len(matches), "matches": matches}
        return ToolResult(ok=True, tool_name="search_files", content=json.dumps(payload))

    def _run_related_files(self, args: Dict[str, Any]) -> ToolResult:
        rel = str(args.get("path") or "").strip()
        query = str(args.get("query") or "").strip()
        limit = max(1, min(25, int(args.get("limit", 10))))

        ref_rel: Optional[str] = None
        seed_terms: Set[str] = set()
        if rel:
            ref_path = self.sandbox.resolve_read(rel)
            ref_rel = self.sandbox.relativize(ref_path)
            text, err = self._read_utf8_capped(ref_path)
            if err is not None or text is None:
                return ToolResult(ok=False, tool_name="related_files", content="", error=err or "Unreadable file")
            seed_terms = _extract_terms(ref_rel + "\n" + text)
        elif query:
            seed_terms = _extract_terms(query)
        else:
            return ToolResult(ok=False, tool_name="related_files", content="", error="Either 'path' or 'query' is required")

        scored: List[Tuple[float, int, str]] = []
        for fpath in self._iter_safe_files(self.sandbox.root):
            candidate_rel = self.sandbox.relativize(fpath)
            if candidate_rel == ref_rel:
                continue
            text, err = self._read_utf8_capped(fpath)
            if err is not None or text is None:
                continue
            cand_terms = _extract_terms(candidate_rel + "\n" + text)
            if not cand_terms or not seed_terms:
                continue
            overlap = len(seed_terms & cand_terms)
            if overlap <= 0:
                continue
            jaccard = overlap / float(len(seed_terms | cand_terms))
            scored.append((jaccard, overlap, candidate_rel))

        scored.sort(key=lambda item: (-item[0], -item[1], item[2]))
        results = [{"path": p, "score": round(score, 4), "shared_terms": ov} for score, ov, p in scored[:limit]]
        return ToolResult(
            ok=True,
            tool_name="related_files",
            content=json.dumps({"reference": ref_rel or query, "related": results}),
        )

    def _run_write_file(self, args: Dict[str, Any]) -> ToolResult:
        rel = args.get("path", "")
        content = args.get("content")
        if not isinstance(content, str):
            return ToolResult(ok=False, tool_name="write_file", content="", error="'content' must be a string")
        raw_bytes = content.encode("utf-8")
        if len(raw_bytes) > min(self.limits.max_write_bytes, MAX_WRITE_BYTES):
            return ToolResult(
                ok=False,
                tool_name="write_file",
                content="",
                error=f"Proposed content ({len(raw_bytes)} B) exceeds max_write_bytes ({self.limits.max_write_bytes} B)",
            )

        target = self.sandbox.resolve_write(rel)
        norm_rel = self.sandbox.relativize(target)
        if target.exists():
            base_sha = self.sandbox.sha256_file(target)
            old_text, err = self._read_utf8_capped(target)
            old_text = old_text if (err is None and old_text is not None) else ""
        else:
            base_sha = ""
            old_text = ""

        diff_text = _make_unified_diff(norm_rel, old_text, content)
        clipped_diff, _ = _clip_text(diff_text, self.limits.max_output_chars)
        proposal = StagedWriteProposal(
            tool_name="write_file",
            rel_path=norm_rel,
            base_sha256=base_sha,
            new_content=content,
            diff=clipped_diff,
            bytes_new=len(raw_bytes),
            reason=str(args.get("reason") or ""),
        )
        summary = {
            "status": "staged_for_approval",
            "path": norm_rel,
            "base_sha256": base_sha,
            "bytes_new": len(raw_bytes),
            "diff_preview": clipped_diff,
        }
        return ToolResult(ok=True, tool_name="write_file", content=json.dumps(summary, indent=2), staged_proposal=proposal)

    def _run_edit_file(self, args: Dict[str, Any]) -> ToolResult:
        rel = args.get("path", "")
        target_str = args.get("target")
        replacement = args.get("replacement")
        if not isinstance(target_str, str) or target_str == "":
            return ToolResult(ok=False, tool_name="edit_file", content="", error="'target' must be a non-empty string")
        if not isinstance(replacement, str):
            return ToolResult(ok=False, tool_name="edit_file", content="", error="'replacement' must be a string")

        path_obj = self.sandbox.resolve_write(rel)
        if not path_obj.exists() or not path_obj.is_file():
            return ToolResult(ok=False, tool_name="edit_file", content="", error=f"File does not exist: {rel}")

        norm_rel = self.sandbox.relativize(path_obj)
        base_sha = self.sandbox.sha256_file(path_obj)
        old_text, err = self._read_utf8_capped(path_obj)
        if err is not None or old_text is None:
            return ToolResult(ok=False, tool_name="edit_file", content="", error=err or "Unreadable file")

        start_line = args.get("start_line")
        end_line = args.get("end_line")
        if start_line is not None or end_line is not None:
            lines = old_text.splitlines(keepends=True)
            s_idx = max(0, int(start_line or 1) - 1)
            e_idx = min(len(lines), int(end_line or len(lines)))
            prefix = "".join(lines[:s_idx])
            window = "".join(lines[s_idx:e_idx])
            suffix = "".join(lines[e_idx:])
            count = window.count(target_str)
            if count == 0:
                return ToolResult(ok=False, tool_name="edit_file", content="", error="Target not found in specified line range")
            if count > 1:
                return ToolResult(
                    ok=False,
                    tool_name="edit_file",
                    content="",
                    error=f"Ambiguous edit: target matched {count} times in line range; provide more context",
                )
            new_text = prefix + window.replace(target_str, replacement, 1) + suffix
        else:
            count = old_text.count(target_str)
            if count == 0:
                return ToolResult(ok=False, tool_name="edit_file", content="", error="Target text not found in file")
            if count > 1:
                return ToolResult(
                    ok=False,
                    tool_name="edit_file",
                    content="",
                    error=f"Ambiguous edit: target matched {count} times; narrow with start_line/end_line or more context",
                )
            new_text = old_text.replace(target_str, replacement, 1)

        raw_bytes = new_text.encode("utf-8")
        if len(raw_bytes) > min(self.limits.max_write_bytes, MAX_WRITE_BYTES):
            return ToolResult(
                ok=False,
                tool_name="edit_file",
                content="",
                error=f"Edited content ({len(raw_bytes)} B) exceeds max_write_bytes ({self.limits.max_write_bytes} B)",
            )

        diff_text = _make_unified_diff(norm_rel, old_text, new_text)
        clipped_diff, _ = _clip_text(diff_text, self.limits.max_output_chars)
        proposal = StagedWriteProposal(
            tool_name="edit_file",
            rel_path=norm_rel,
            base_sha256=base_sha,
            new_content=new_text,
            diff=clipped_diff,
            bytes_new=len(raw_bytes),
            reason=str(args.get("reason") or ""),
        )
        summary = {
            "status": "staged_for_approval",
            "path": norm_rel,
            "base_sha256": base_sha,
            "bytes_new": len(raw_bytes),
            "diff_preview": clipped_diff,
        }
        return ToolResult(ok=True, tool_name="edit_file", content=json.dumps(summary, indent=2), staged_proposal=proposal)

    def _run_sense_probe(self, name: str, args: Dict[str, Any]) -> ToolResult:
        rel = args.get("path", "")
        target = self.sandbox.resolve_read(rel)
        payload: Dict[str, Any] = {
            "status": "verified_file_metadata",
            "path": self.sandbox.relativize(target),
            "bytes": target.stat().st_size,
            "sha256": self.sandbox.sha256_file(target),
        }
        if name == "look":
            fmt, w, h = inspect_image_bytes(target.read_bytes(), target.name)
            payload["format"] = fmt
            payload["width"] = w
            payload["height"] = h
        return ToolResult(ok=True, tool_name=name, content=json.dumps(payload, indent=2))
